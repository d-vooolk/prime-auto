export interface BrandServiceDefinition {
    /** Ключ услуги */
    key: string;
    /** Базовый URL родительской страницы услуги */
    basePath: string;
    /** Название услуги в именительном падеже */
    label: string;
    /** Заголовок H1 страницы марки */
    h1: (brand: CarBrand) => string;
    /** <title> страницы марки */
    title: (brand: CarBrand) => string;
    /** meta description страницы марки */
    description: (brand: CarBrand) => string;
    /** Вступительный текст под H1 */
    intro: (brand: CarBrand) => string;
    /** Что входит в услугу */
    bullets: string[];
    priceTitle: string;
    priceDataSource: PriceDataSourceInterface[];
    /** Блок «Что мы делаем» родительской страницы услуги */
    proposalList: OurProposalBlockList[];
    /** Вопрос-ответ. brand не передаётся на общей странице услуги */
    faq: (brand?: CarBrand) => FaqItem[];
    /** Хлебные крошки до страницы услуги (без самой марки) */
    trail: {name: string; path: string}[];
}


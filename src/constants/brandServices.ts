export const BRAND_SERVICE_BY_KEY: Record<string, BrandServiceDefinition> = Object.fromEntries(
    BRAND_SERVICES.map((service) => [service.key, service]),
);

export const getBrandService = (key: string): BrandServiceDefinition => {
    const service = BRAND_SERVICE_BY_KEY[key];

    if (!service) {
        throw new Error(`Неизвестная услуга для страниц марок: ${key}`);
    }

    return service;
};

/** Рубрика, в которую попадает статья, если ничего не подошло */
const FALLBACK = 'remont-far';

export const getArticleCategory = (slug: string): ArticleCategory | undefined =>
    ARTICLE_CATEGORIES.find((category) => category.slug === slug);

/** Рубрика статьи: выбранная в админке, иначе — по заголовку и ключевой фразе */
export const categoryOf = (article: {category?: string; title: string; keyword?: string}): ArticleCategory => {
    const chosen = article.category ? getArticleCategory(article.category) : undefined;
    if (chosen) return chosen;
    // ключевая фраза — только запасной вариант: она бывает шире темы статьи
    return ARTICLE_CATEGORIES.find((category) => category.match.test(article.title))
        ?? ARTICLE_CATEGORIES.find((category) => category.match.test(article.keyword ?? ''))
        ?? getArticleCategory(FALLBACK)!;
};

export const categoryPath = (slug: string) => `${NAVIGATION_URL.articles}/tema/${slug}`;
